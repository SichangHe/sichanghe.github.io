use vstd::prelude::*;
verus! {
proof fn check(x: int, y: int)
requires 0 <= x <= 3, 0 <= y <= 3,
{ let z = if x < y { x } else { y };
assert((x == 0 && y == 0 && z == 0) ||
(x == 0 && y == 1 && z == 0) ||
(x == 0 && y == 2 && z == 0) ||
(x == 0 && y == 3 && z == 0) ||
(x == 1 && y == 0 && z == 0) ||
(x == 1 && y == 1 && z == 1) ||
(x == 1 && y == 2 && z == 1) ||
(x == 1 && y == 3 && z == 1) ||
(x == 2 && y == 0 && z == 0) ||
(x == 2 && y == 1 && z == 1) ||
(x == 2 && y == 2 && z == 2) ||
(x == 2 && y == 3 && z == 2) ||
(x == 3 && y == 0 && z == 0) ||
(x == 3 && y == 1 && z == 1) ||
(x == 3 && y == 2 && z == 2) ||
(x == 3 && y == 3 && z == 3)); }
}
fn main() {}
